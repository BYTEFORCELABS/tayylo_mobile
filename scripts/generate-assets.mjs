#!/usr/bin/env node
// Bundles static SVG artwork from the Tayylo web app into a TypeScript
// module so React Native can render it with react-native-svg (SvgXml).
//
//   node scripts/generate-assets.mjs [path-to-web-repo]
//
// Default web repo location: ../tayylo (sibling of this repository).
// Output: src/generated/measurement-svgs.ts — keyed by the same public path
// the web app uses ("/pictures/tayylo-measurement-icons/..."), so the
// shared resolver in src/lib/measurement-art.ts works unchanged.

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(here, "..");
const web = path.resolve(process.argv[2] ?? path.join(root, "..", "tayylo"));
const base = path.join(web, "public", "pictures", "tayylo-measurement-icons");

if (!fs.existsSync(base)) {
  console.error(`Measurement icons not found at ${base}`);
  process.exit(1);
}

function walk(dir) {
  return fs.readdirSync(dir, { withFileTypes: true }).flatMap(d => {
    const p = path.join(dir, d.name);
    return d.isDirectory() ? walk(p) : d.name.endsWith(".svg") ? [p] : [];
  });
}

const entries = walk(base)
  .sort()
  .map(file => {
    const rel = "/pictures/tayylo-measurement-icons/" + path.relative(base, file).split(path.sep).join("/");
    const svg = fs.readFileSync(file, "utf8").replace(/\s*\n\s*/g, " ").trim();
    return `  ${JSON.stringify(rel)}: ${JSON.stringify(svg)},`;
  });

const out = path.join(root, "src", "generated", "measurement-svgs.ts");
fs.mkdirSync(path.dirname(out), { recursive: true });
fs.writeFileSync(
  out,
  `// Auto-generated by scripts/generate-assets.mjs from the web app's\n// public/pictures/tayylo-measurement-icons. Do not edit by hand.\n\n/* eslint-disable */\nexport const MEASUREMENT_SVGS: Record<string, string> = {\n${entries.join("\n")}\n};\n`
);
console.log(`Wrote ${entries.length} SVGs to ${path.relative(root, out)}`);
